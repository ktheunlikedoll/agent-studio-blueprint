#!/usr/bin/env python3
"""model-sync.py — keep the fleet model roster in sync with agent front matter.

SOURCE OF TRUTH : agents/**/*.md front matter (name, model, thinking)
                  + settings.json → subagents.agentOverrides (builtin pins)
DERIVED DOC     : agents/MODEL-ROSTER.md (generated — never hand-edit)

Usage:
  model-sync.py            regenerate agents/MODEL-ROSTER.md
  model-sync.py --check    verify only; exit 1 on drift (CI-style)

Protocol: APPEND_SYSTEM.md standing policy #5 — edit front matter FIRST,
then run this script, then bin/engine-scan.sh, then commit + push.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
AGENTS = ROOT / "agents"
SETTINGS = ROOT / "settings.json"
ROSTER = AGENTS / "MODEL-ROSTER.md"

HEADER = """<!-- GENERATED by bin/model-sync.py — DO NOT EDIT BY HAND.
Source of truth: agents/**/*.md front matter + settings.json (subagents.agentOverrides).
To change a model: edit the agent's `model:`/`thinking:` FIRST, then run
`bin/model-sync.py`, then `bin/engine-scan.sh`, then commit + push.
Protocol: APPEND_SYSTEM.md standing policy #5 (2026-09-08). -->

# Fleet model roster

Every subagent's model, generated from the single source of truth: agent
front matter (builtins from their settings.json pins). Pi (orchestrator)
is set at launch config, not here. Hand-written READMEs carry roles and
policy intent only — this file is the only per-agent model mapping doc.

"""

DEPT_ORDER = {"engine": 0, "studio": 1, "finance": 2, "builtin": 3}


def parse_frontmatter(path):
    text = path.read_text(encoding="utf-8")
    m = re.match(r"\A---\s*\n(.*?)\n---\s*\n", text, re.S)
    if not m:
        return {}
    fm = {}
    for line in m.group(1).splitlines():
        if ":" in line and not line.startswith((" ", "-", "#")):
            key, val = line.split(":", 1)
            fm[key.strip()] = val.strip()
    return fm


def collect():
    rows = []
    for path in sorted(AGENTS.rglob("*.md")):
        if path.name in ("README.md", "MODEL-ROSTER.md"):
            continue
        fm = parse_frontmatter(path)
        if "name" not in fm or "model" not in fm:
            sys.exit(f"FAIL: {path} missing name/model front matter (run bin/engine-scan.sh)")
        dept = "engine" if path.parent == AGENTS else path.parent.relative_to(AGENTS).as_posix()
        rows.append((dept, fm["name"], fm["model"], fm.get("thinking", "default")))
    if SETTINGS.exists():
        overrides = json.loads(SETTINGS.read_text(encoding="utf-8")).get("subagents", {}).get("agentOverrides", {})
        for name, cfg in sorted(overrides.items()):
            if not isinstance(cfg, dict) or cfg.get("disabled"):
                continue
            if cfg.get("model"):
                rows.append(("builtin", f"{name} (builtin)", cfg["model"], str(cfg.get("thinking", "default"))))
    return rows


def render(rows):
    lines = ["| Agent | Dept | Model | Thinking |", "|---|---|---|---|"]
    for dept, name, model, thinking in sorted(rows, key=lambda r: (DEPT_ORDER.get(r[0], 9), r[1])):
        lines.append(f"| `{name}` | {dept} | `{model}` | {thinking} |")
    return "\n".join(lines) + "\n"


def main():
    check = "--check" in sys.argv
    desired = HEADER + render(collect())
    if check:
        actual = ROSTER.read_text(encoding="utf-8") if ROSTER.exists() else ""
        if actual == desired:
            print("  model roster in sync")
            return 0
        print(f"  FAIL: {ROSTER.name} out of sync with front matter — run: bin/model-sync.py")
        return 1
    ROSTER.write_text(desired, encoding="utf-8")
    print(f"  wrote agents/{ROSTER.name} ({len(desired.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
