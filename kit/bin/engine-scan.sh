#!/usr/bin/env bash
# engine-scan.sh — engine reliability scan (doctrine self-healing protocol, step 5)
# Run after any engine patch/change. Exit 0 = clean, 1 = findings.
AGENTS="$(cd "$(dirname "$0")/.." && pwd)/agents"
FAIL=0

echo "── 1. Frontmatter validity (name + model present) ──"
while IFS= read -r f; do
  base=$(basename "$f"); [ "$base" = "README.md" ] && continue
  [ "$base" = "MODEL-ROSTER.md" ] && continue   # generated by bin/model-sync.py, no front matter
  if ! grep -q "^name: " "$f" || ! grep -q "^model: \S" "$f"; then echo "  FAIL: $f"; FAIL=1; fi
done < <(find "$AGENTS" -name "*.md")
echo "  ok"

echo "── 2. Stale path patterns ──"
HITS=$(grep -rln "/home/hermes\|\.hermes/\|output/\[run-id\]" "$AGENTS" 2>/dev/null)
if [ -n "$HITS" ]; then echo "$HITS" | sed 's/^/  FAIL: /'; FAIL=1; else echo "  ok"; fi

echo "── 3. Tool-vs-prompt mismatch (shell verbs without bash) ──"
while IFS= read -r f; do
  base=$(basename "$f"); [ "$base" = "README.md" ] && continue
  tools=$(grep -m1 "^tools:" "$f")
  [ -z "$tools" ] && continue
  if ! echo "$tools" | grep -q "bash"; then
    n=$(awk 'c{print} /^---$/{if(c)exit; c=1}' "$f" | grep -cE "bash |ffmpeg|npx |python3 |magick |pandoc")
    [ "$n" -gt 0 ] && { echo "  FAIL: $f (uses shell verbs, no bash)"; FAIL=1; }
  fi
done < <(find "$AGENTS" -name "*.md")
echo "  ok"

echo "── 4. Manager/director run-discipline tripwire (RH-001) — string presence only, NOT behavioral verification ──"
for f in "$AGENTS/studio/art-director.md" "$AGENTS/studio/tech-director.md" "$AGENTS/learnforge/director.md" "$AGENTS/youtube/director.md" "$AGENTS/packforge/builder.md"; do
  grep -q "bg_wait" "$f" || { echo "  FAIL: $f (no bg_wait in allowlist — blocking tool is the Pi builtin; the old subagent_wait name is a ghost from the pre-2026-09 RH-001 patch)"; FAIL=1; }
  grep -q "RH-001" "$f" || { echo "  FAIL: $f (no run-discipline rule)"; FAIL=1; }
done
echo "  ok"

echo "── 5. Declared tool names vs known harness tools (ghost-tool tripwire; static harness list + dynamic MCP discovery from mcp.json — does NOT verify runtime grants) ──"
KNOWN_TOOLS="read write edit bash ls find grep web_search source_check fetch_content get_search_content subagent bg_wait mcp mcpScript subagent_supervisor create_goal get_goal"
MCP_TOOLS=$(node "$(dirname "$0")/mcp-tool-names.mjs" 2>/dev/null)
[ -n "$MCP_TOOLS" ] && echo "  mcp.json tools discovered: $(echo $MCP_TOOLS | tr '\n' ' ')"
ALL_KNOWN="$KNOWN_TOOLS $MCP_TOOLS"
while IFS= read -r f; do
  base=$(basename "$f"); [ "$base" = "README.md" ] && continue
  tools=$(grep -m1 "^tools:" "$f"); [ -z "$tools" ] && continue
  BAD=$(echo "$tools" | sed 's/^tools:[[:space:]]*//' | tr ',' '\n' | tr -d ' \r' | grep -v '^$' | while IFS= read -r t; do
    ok=0; for k in $ALL_KNOWN; do [ "$t" = "$k" ] && ok=1; done
    [ $ok -eq 0 ] && echo "$t"
  done)
  [ -n "$BAD" ] && { echo "  FAIL: $f (declared tool(s) not in known harness set: $BAD — ghost-tool class)"; FAIL=1; }
done < <(find "$AGENTS" -name "*.md")
echo "  ok"

echo "── 6. Model roster sync (front matter → MODEL-ROSTER.md, standing policy #5) ──"
if python3 "$(dirname "$0")/model-sync.py" --check >/dev/null 2>&1; then echo "  ok"; else
  echo "  FAIL: agents/MODEL-ROSTER.md out of sync with front matter — run: bin/model-sync.py"; FAIL=1
fi

[ $FAIL -eq 0 ] && echo "── ENGINE SCAN: CLEAN ──" || echo "── ENGINE SCAN: FINDINGS ABOVE ──"
exit $FAIL
